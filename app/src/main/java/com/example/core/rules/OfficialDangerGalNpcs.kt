package com.example.core.rules

data class DgdNpcEntry(
    val factionId: String,
    val factionNamePt: String,
    val npc: OfficialNpcSpec
)

private fun dgdNpc(
    factionId: String,
    factionNamePt: String,
    id: String,
    name: String,
    tier: NpcThreatTier,
    summaryPt: String,
    stats: IntArray, // [INT, REF, DEX, TECH, COOL, WILL, MOVE, BODY, EMP]
    hp: Int,
    sp: Int,
    armorLabel: String,
    roleAbility: String?,
    weapons: List<OfficialNpcWeaponSpec>,
    programs: List<String> = emptyList(),
    gear: List<String> = emptyList(),
    skills: String
): DgdNpcEntry = DgdNpcEntry(
    factionId = factionId,
    factionNamePt = factionNamePt,
    npc = OfficialNpcSpec(
        id = "dgd_$id",
        namePt = name,
        nameEn = name,
        tier = tier,
        roleSummaryPt = "$factionNamePt • $summaryPt",
        intelligence = stats[0],
        reflexes = stats[1],
        dexterity = stats[2],
        technique = stats[3],
        cool = stats[4],
        willpower = stats[5],
        move = stats[6],
        body = stats[7],
        empathy = stats[8],
        hp = hp,
        seriouslyWounded = (hp + 1) / 2,
        deathSave = stats[7],
        headArmorSp = sp,
        bodyArmorSp = sp,
        armorLabelPt = armorLabel,
        armorPenaltyActive = sp >= 12 && !armorLabel.contains("Subdermal", true),
        roleAbilityLabelPt = roleAbility,
        weapons = weapons,
        programs = programs,
        gearAndCyberwarePt = gear,
        keySkillBasesPt = skills
    )
)

private fun w(name: String, dice: Int, q: WeaponQuality = WeaponQuality.STANDARD, notes: String = "") =
    OfficialNpcWeaponSpec(name, dice, q, notes)

